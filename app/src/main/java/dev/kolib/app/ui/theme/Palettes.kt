/**
 * The palettes of the Clean looks in other colours, a light and a dark of each. They're Mihon's
 * (github.com/mihonapp/mihon, Apache License 2.0), which follow Catppuccin's (catppuccin.com, MIT, (c) 2021 Catppuccin),
 * Nord's (nordtheme.com), Tokyo Night's (github.com/folke/tokyonight.nvim) and others' own. Here the darks are on
 * black, as in Mihon with pure black on; the surface roles some don't give are mixed from their surface and its text,
 * and Material's own error colours stand in where they give none; and where a text colour didn't stand out enough
 * from what it's on for KoLib's looks (see LooksTest), it's taken a little darker or lighter. Dynamic takes its
 * colours from the wallpaper, on Android 12 and later.
 */
enum class Palette(val label: String) {
    DYNAMIC(tr("Dynamic")),
    CATPPUCCIN("Catppuccin"),
    GREEN_APPLE(tr("Green Apple")),
    LAVENDER(tr("Lavender")),
    MIDNIGHT_DUSK(tr("Midnight Dusk")),
    NORD("Nord"),
    STRAWBERRY(tr("Strawberry Daiquiri")),
    TAKO("Tako"),
    TEAL_TURQUOISE(tr("Teal & Turquoise")),
    TIDAL_WAVE(tr("Tidal Wave")),
    YIN_YANG(tr("Yin & Yang")),
    YOTSUBA("Yotsuba"),
    TOKYO_NIGHT("Tokyo Night"),
    MONOCHROME(tr("Monochrome")),
    ;

    companion object {
        /** Dynamic's colours come from Android 12 on. */
        val dynamicAvailable get() = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S

        /** The palettes there are on this device. */
        val shown get() = entries.filter { it != DYNAMIC || dynamicAvailable }
    }
}

private val paletteLooks = HashMap<Pair<Palette, Boolean>, Look>()

/** The Clean look in [palette]'s colours, light or [dark] ([context]: for Dynamic's, from the wallpaper). */
internal fun paletteLook(palette: Palette, dark: Boolean, context: Context?): Look {
    if (palette == Palette.DYNAMIC) {
        val scheme = dynamicScheme(context, dark) ?: return if (dark) CleanDarkLook else CleanLightLook
        return cleanLook(scheme, dark)
    }
    return paletteLooks.getOrPut(palette to dark) { cleanLook(paletteScheme(palette, dark), dark) }
}

/** The Clean look's lettering, corners and plain backdrop, in [scheme]'s colours. */
private fun cleanLook(scheme: ColorScheme, dark: Boolean): Look {
    val accent = scheme.primary
    return Look(
        scheme,
        KoLibStyle(
            dark = dark, backdrop = Backdrop.FLAT,
            gold = accent, onGold = scheme.onPrimary,
            markGold = listOf(lerp(accent, Color.White, 0.45f), accent, lerp(accent, Color.Black, 0.35f)),
            hairline = scheme.onSurface.copy(alpha = if (dark) 0.10f else 0.09f),
            badge = if (dark) Color.Black.copy(alpha = 0.66f) else Color(0xFF111114).copy(alpha = 0.62f), onBadge = Color.White,
            shadow = if (dark) Color.Black else lerp(scheme.onSurface, Color.Black, 0.4f),
        ),
        typographyFor(Lettering.SANS),
        softCorners(8, 10, 14, 18, 26),
    )
}

/** The wallpaper's colours, the dark on black; null before Android 12, or with nothing to ask. */
private fun dynamicScheme(context: Context?, dark: Boolean): ColorScheme? {
    if (context == null || !Palette.dynamicAvailable) return null
    return runCatching {
        if (dark) {
            dynamicDarkColorScheme(context).copy(
                background = Color.Black, surface = Color.Black, surfaceDim = Color.Black, surfaceContainerLowest = Color.Black,
            )
        } else {
            dynamicLightColorScheme(context)
        }
    }.getOrNull()
}

private fun paletteScheme(palette: Palette, dark: Boolean): ColorScheme = when (palette) {
    Palette.DYNAMIC -> if (dark) CleanDarkLook.scheme else CleanLightLook.scheme
    Palette.CATPPUCCIN -> if (dark) CatppuccinDark else CatppuccinLight
    Palette.GREEN_APPLE -> if (dark) GreenAppleDark else GreenAppleLight
    Palette.LAVENDER -> if (dark) LavenderDark else LavenderLight
    Palette.MIDNIGHT_DUSK -> if (dark) MidnightDuskDark else MidnightDuskLight
    Palette.NORD -> if (dark) NordDark else NordLight
    Palette.STRAWBERRY -> if (dark) StrawberryDark else StrawberryLight
    Palette.TAKO -> if (dark) TakoDark else TakoLight
    Palette.TEAL_TURQUOISE -> if (dark) TealTurquoiseDark else TealTurquoiseLight
    Palette.TIDAL_WAVE -> if (dark) TidalWaveDark else TidalWaveLight
    Palette.YIN_YANG -> if (dark) YinYangDark else YinYangLight
    Palette.YOTSUBA -> if (dark) YotsubaDark else YotsubaLight
    Palette.TOKYO_NIGHT -> if (dark) TokyoNightDark else TokyoNightLight
    Palette.MONOCHROME -> if (dark) MonochromeDark else MonochromeLight
}

